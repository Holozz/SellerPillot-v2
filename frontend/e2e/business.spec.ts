import { test,expect } from '@playwright/test'

test('卖家上传规则、检查检索、跟踪任务并确认商品标题',async({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/')
  await page.getByLabel('用户名').fill('demo')
  await page.getByLabel('密码',{exact:true}).fill(process.env.DEMO_PASSWORD||'LocalPreview123!')
  await page.getByRole('button',{name:'登录工作台',exact:true}).click()
  await expect(page.getByRole('heading',{name:'经营决策与执行'})).toBeVisible()
  await page.getByRole('button',{name:'知识中心',exact:true}).click()
  await page.getByRole('button',{name:'创建知识库',exact:true}).click()
  await page.locator('input[type=file]').setInputFiles({name:'title-rules.md',mimeType:'text/markdown',
    buffer:Buffer.from('# 标题规则\n\nJAR-001 商品标题必须保留容量500ml，禁止使用 best seller 等排名承诺。')})
  await page.getByRole('button',{name:'上传并处理',exact:true}).click()
  await expect(page.getByText('资料已接收，处理完成后自动发布。')).toBeVisible()
  await page.getByRole('button',{name:'任务中心',exact:true}).click()
  await expect(page.locator('.sp-task').first()).toContainText('已完成',{timeout:30000})
  await page.getByRole('button',{name:'知识中心',exact:true}).click()
  await page.getByLabel('问题',{exact:true}).fill('JAR-001 标题规则')
  await page.getByRole('button',{name:'测试检索',exact:true}).click()
  await expect(page.locator('.sp-source').first()).toBeVisible()
  await page.getByRole('button',{name:'操作审批',exact:true}).click()
  await page.locator('.sp-inline select').selectOption({index:1})
  const title='Glass Storage Jar 500ml '+Date.now()
  await page.getByPlaceholder('建议的新标题').fill(title)
  await page.getByRole('button',{name:'保存待审核草稿'}).click()
  const proposal=page.locator('.sp-proposal').filter({hasText:title})
  page.once('dialog',dialog=>dialog.accept())
  await proposal.getByRole('button',{name:'确认应用',exact:true}).click()
  await expect(proposal).toContainText('已应用')
  await page.screenshot({path:'../docs/verification/approvals-desktop.png',fullPage:true})
  await page.getByRole('button',{name:'运营助手',exact:true}).click()
  await page.getByLabel('本次任务').fill('检查近七天经营数据')
  await page.getByLabel('仅检查近七天数据查询（不调用模型）').check()
  await page.getByRole('button',{name:'开始分析',exact:true}).click()
  await expect(page.locator('.sp-answer')).toContainText('离线检查已完成',{timeout:30000})
  await page.screenshot({path:'../docs/verification/assistant-desktop.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  await page.screenshot({path:'../docs/verification/assistant-mobile.png',fullPage:true})
  expect(errors).toEqual([])
})
